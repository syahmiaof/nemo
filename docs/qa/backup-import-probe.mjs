import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const path=name=>fileURLToPath(new URL(`./artifacts/${name}`,import.meta.url));
const b=await chromium.launch();const c=await b.newContext({viewport:{width:1440,height:900}});const p=await c.newPage();
const result={};await p.goto('http://127.0.0.1:4173/settings');await p.waitForTimeout(300);
if(await p.getByRole('dialog',{name:'Welcome to Nemo'}).count())await p.keyboard.press('Escape');
await p.getByRole('button',{name:'Skip customization'}).click({timeout:4000}).catch(()=>{});
await p.getByRole('tab',{name:/Data & Backups/}).click();
await p.locator('input[type=file][accept*="json"]').setInputFiles(path('disposable-demo-backup.json'));
const dialog=p.getByRole('dialog',{name:'Confirm Backup Restore'});await dialog.waitFor();
result.summary=(await dialog.innerText()).slice(0,300);
await dialog.getByRole('button',{name:'Confirm Restore'}).click();
await p.getByText('Workspace restored successfully').waitFor({timeout:10000});
await p.goto('http://127.0.0.1:4173/projects');await p.waitForTimeout(300);
if(await p.getByRole('dialog',{name:'Welcome to Nemo'}).count())await p.keyboard.press('Escape');
result.projectVisible=await p.getByRole('heading',{name:'Orbit Analytics'}).isVisible();
result.workspaceMode=await p.locator('.workspace-status').innerText();
await p.screenshot({path:path('backup-restored-projects.png')});
await c.close();await b.close();await writeFile(path('backup-import-results.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
